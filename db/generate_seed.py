"""Create db/seed.sql with positions for the 50 demo parking spaces.

Run this file from any folder with: python3 db/generate_seed.py
Map units are roughly metres. x points right and y points down.
"""

from pathlib import Path

HALF_ROAD_WIDTH = 3.5

# For each size class: (bay width, bay depth).
BAY_SIZES = {
    1: (2.4, 4.6),
    2: (2.7, 5.0),
    3: (3.0, 5.6),
    4: (3.4, 6.0),
}
LABEL_PREFIXES = {1: "C", 2: "S", 3: "U", 4: "F"}
EXPECTED_COUNTS = {1: 10, 2: 20, 3: 12, 4: 8}

# Each row says which road it is beside, where it starts, and which bays to add.
# A "gap" leaves empty space between groups of bays.
ROWS = [
    ("up-down", 14, "west", 40, [(1, 6)]),
    ("across", 12, "below", 38, [(2, 6), ("gap", 4), (3, 3)]),
    ("across", 36, "above", 22, [(3, 3), ("gap", 3), (2, 6)]),
    ("across", 36, "below", 34, [(2, 5), ("gap", 5), (3, 3)]),
    ("across", 60, "above", 20, [(3, 3), (2, 3)]),
    ("across", 60, "below", 22, [(1, 4)]),
    ("up-down", 76, "east", 17, [(4, 8)]),
]


def make_slot(row_type, road_position, side, along, size_class, number):
    """Calculate one bay's name, size, map rectangle, and road access point."""
    bay_width, bay_depth = BAY_SIZES[size_class]

    if row_type == "across":
        x = along
        if side == "below":
            y = road_position + HALF_ROAD_WIDTH
        else:
            y = road_position - HALF_ROAD_WIDTH - bay_depth
        width = bay_width
        height = bay_depth
        access_x = x + width / 2
        access_y = road_position
    else:
        if side == "east":
            x = road_position + HALF_ROAD_WIDTH
        else:
            x = road_position - HALF_ROAD_WIDTH - bay_depth
        y = along
        width = bay_depth
        height = bay_width
        access_x = road_position
        access_y = y + height / 2

    return {
        "label": f"{LABEL_PREFIXES[size_class]}{number}",
        "size_class": size_class,
        "x": x,
        "y": y,
        "width": width,
        "height": height,
        "access_x": access_x,
        "access_y": access_y,
    }


def build_slots():
    """Build all parking spaces in the same order as the original layout."""
    counts = {size_class: 0 for size_class in EXPECTED_COUNTS}
    slots = []

    for row_type, road_position, side, row_start, bay_groups in ROWS:
        along = row_start

        for size_class, amount in bay_groups:
            if size_class == "gap":
                along += amount
                continue

            bay_width, _ = BAY_SIZES[size_class]
            for _ in range(amount):
                counts[size_class] += 1
                slot = make_slot(
                    row_type,
                    road_position,
                    side,
                    along,
                    size_class,
                    counts[size_class],
                )
                slots.append(slot)
                along += bay_width

    if counts != EXPECTED_COUNTS:
        raise ValueError(f"Unexpected number of bays: {counts}")

    return slots


def slots_overlap(first, second):
    """Return True when two bay rectangles share some area."""
    first_is_left = first["x"] < second["x"] + second["width"]
    second_is_left = second["x"] < first["x"] + first["width"]
    first_is_above = first["y"] < second["y"] + second["height"]
    second_is_above = second["y"] < first["y"] + first["height"]
    return first_is_left and second_is_left and first_is_above and second_is_above


def check_for_overlaps(slots):
    """Stop seed generation if any two parking bays overlap."""
    for first_index, first in enumerate(slots):
        for second in slots[first_index + 1:]:
            if slots_overlap(first, second):
                raise ValueError(f"Parking bays overlap: {first['label']} and {second['label']}")


def make_seed_sql(slots):
    """Turn the calculated bay positions into an idempotent SQL insert."""
    header = [
        "-- GENERATED by db/generate_seed.py. Do not edit by hand; change the script and run it again.",
        "-- Safe to run many times: positions are updated, but a slot's status is never changed.",
        "INSERT INTO slots (label, size_class, x, y, width, height, access_x, access_y) VALUES",
    ]

    value_rows = []
    for slot in slots:
        values = (
            f"  ('{slot['label']}', {slot['size_class']}, "
            f"{slot['x']:.2f}, {slot['y']:.2f}, "
            f"{slot['width']:.2f}, {slot['height']:.2f}, "
            f"{slot['access_x']:.2f}, {slot['access_y']:.2f})"
        )
        value_rows.append(values)

    footer = [
        "ON CONFLICT (lot_id, label) DO UPDATE SET",
        "  size_class = EXCLUDED.size_class, x = EXCLUDED.x, y = EXCLUDED.y,",
        "  width = EXCLUDED.width, height = EXCLUDED.height,",
        "  access_x = EXCLUDED.access_x, access_y = EXCLUDED.access_y;",
    ]

    return "\n".join(header + [",\n".join(value_rows)] + footer) + "\n"


def main():
    slots = build_slots()
    check_for_overlaps(slots)

    output_file = Path(__file__).with_name("seed.sql")
    output_file.write_text(make_seed_sql(slots))
    print(len(slots), "slots written")


if __name__ == "__main__":
    main()
